import { expect, test } from '@playwright/test'

test('builds a box with keyboard controls and preserves existing basket items', async ({ page, baseURL }) => {
  const origin = new URL(baseURL!).origin
  await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort())
  await page.goto('/clinics')
  await page.getByRole('button', { name: 'Add one Salted Caramel', exact: true }).click()
  await page.goto('/')
  await page.getByRole('link', { name: 'Build a cookie box', exact: true }).click()
  await expect(page).toHaveURL(/\/clinics#build-your-box$/)
  // The Box Builder is a section of Order Cookies, which also shows the basket total, so the box's
  // own total is read inside the builder.
  const builder = page.getByRole('region', { name: 'Cookie box builder' })
  const submit = page.getByRole('button', { name: 'Add box to basket' })
  await expect(submit).toBeDisabled()
  await expect(page.getByRole('heading', { name: 'Build Your Own Cookie Box' })).toBeVisible()
  const slots = page.getByRole('list', { name: 'Box slots' }).getByRole('listitem')
  await expect(slots).toHaveCount(4)
  const dialog = page.getByRole('dialog')
  const firstSlot = slots.nth(0).getByRole('button')
  await firstSlot.press('Enter')
  await expect(dialog.getByRole('listitem')).toHaveCount(6)
  await page.keyboard.press('Escape')
  await expect(firstSlot).toBeFocused()
  await firstSlot.press('Enter')
  await dialog.getByRole('button', { name: /Classic Chocolate Chip/ }).press('Enter')
  await expect(page.getByText('1 of 4 selected')).toBeVisible()
  await expect(page.getByText('Choose 3 more cookies to complete your box.')).toBeVisible()
  await expect(builder.getByText(/Total:.*3[.,]50/)).toBeVisible()
  await slots.nth(2).getByRole('button').press('Enter')
  await dialog.getByRole('button', { name: /Classic Chocolate Chip/ }).press('Enter')
  await expect(builder.getByText(/Total:.*7[.,]00/)).toBeVisible()
  const removeFirst = slots.nth(0).getByRole('button', { name: /Remove Classic Chocolate Chip/ })
  await removeFirst.press('Enter')
  await expect(firstSlot).toBeFocused()
  await expect(slots.nth(2)).toContainText('Classic Chocolate Chip')
  await expect(builder.getByText(/Total:.*3[.,]50/)).toBeVisible()
  await firstSlot.press('Enter')
  await dialog.getByRole('button', { name: /Red Velvet/ }).press('Enter')
  await expect(slots.nth(0)).toContainText('Red Velvet')
  await expect(builder.getByText(/Total:.*7[.,]45/)).toBeVisible()
  const chocolateLovers = page.getByRole('button', { name: 'Chocolate Lovers' })
  await chocolateLovers.press('Enter')
  await expect(dialog.getByRole('heading', { name: 'Replace your selection?' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Keep my selection' }).press('Enter')
  await expect(slots.nth(0)).toContainText('Red Velvet')
  await chocolateLovers.press('Enter')
  await dialog.getByRole('button', { name: 'Replace selection' }).press('Enter')
  await expect(page.getByText('4 of 4 selected')).toBeVisible()
  await expect(slots.filter({ hasText: 'Double Chocolate' })).toHaveCount(2)
  await expect(page.getByRole('button', { name: /Add a cookie to slot/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Reset box' }).press('Enter')
  await expect(page.getByText('0 of 4 selected')).toBeVisible()
  await expect(submit).toBeDisabled()
  await page.getByRole('button', { name: 'A Little Bit of Everything' }).press('Enter')
  await expect(page.getByText('4 of 4 selected')).toBeVisible()
  await submit.press('Enter')
  await expect(page.getByRole('status').filter({ hasText: 'Box added to your basket' })).toBeVisible()
  await expect(submit).toBeDisabled()
  await page.getByRole('link', { name: 'Review basket' }).press('Enter')
  const basket = page.getByRole('region', { name: /Review your basket/ })
  await expect(basket).toContainText('Salted Caramel × 2')
  await expect(basket).toContainText('Classic Chocolate Chip × 1')
  await basket.getByRole('button', { name: 'Increase basket quantity of Classic Chocolate Chip' }).press('Enter')
  await expect(basket).toContainText('Classic Chocolate Chip × 2')
  await basket.getByRole('button', { name: 'Remove Classic Chocolate Chip from basket' }).press('Enter')
  await expect(basket).not.toContainText('Classic Chocolate Chip')
  await basket.getByRole('link', { name: 'Proceed to checkout' }).press('Enter')
  await page.getByLabel('Name (made-up)').fill('Example customer')
  await page.getByLabel('Email (made-up)').fill('invalid')
  await expect.poll(() => page.getByLabel('Email (made-up)').evaluate(input => !(input as HTMLInputElement).validity.valid)).toBe(true)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('rejects a guest from analytics HTML and CSV', async ({ request }) => {
  const html = await request.get('/admin/order-analytics')
  const body = await html.text()
  // Next may stream the not-found boundary after committing a 200 response.
  expect(html.status() === 404 || (html.status() === 200 && body.includes('NEXT_HTTP_ERROR_FALLBACK;404'))).toBe(true)
  expect(body).not.toContain('Total test order value')
  const csv = await request.get('/api/order-analytics/export')
  expect(csv.status()).toBe(403)
  expect(csv.headers()['cache-control']).toContain('no-store')
})

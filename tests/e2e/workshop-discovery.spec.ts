import { expect, test } from '@playwright/test'

test('finds workshops from the homepage, navigation, and topic by keyboard', async ({ page }) => {
  await page.goto('/')
  const preview = page.getByRole('region', { name: 'More than cookies. An experience.' })
  const title = 'Classic Chocolate Chip'
  const href = '/workshops/classic-chocolate-chip'
  await expect(preview).toContainText('fictional university project')
  await expect(preview.getByRole('img', { name: 'Freshly baked chocolate chip cookies with baking ingredients.' })).toBeVisible()
  await preview.getByRole('link', { name: title }).press('Enter')
  await expect(page).toHaveURL(new RegExp(href + '$'))
  await page.getByRole('link', { name: 'Chocolate Lovers', exact: true }).press('Enter')
  await expect(page).toHaveURL(/\/topics\/chocolate-lovers$/)
  await page.getByRole('link', { name: 'Filter the workshop list by this topic' }).press('Enter')
  await expect(page).toHaveURL(/\?topic=chocolate-lovers#workshops$/)
  const overview = page.getByRole('region', { name: 'Explore the workshops', exact: true })
  await expect(overview.getByRole('article')).toHaveCount(1)
  await overview.getByRole('link', { name: title }).press('Enter')
  await page.getByRole('link', { name: 'Back to the filtered workshops' }).press('Enter')
  await expect(page).toHaveURL(/\?topic=chocolate-lovers#workshops$/)
  await overview.getByRole('link', { name: 'Show all workshops' }).press('Enter')
  await expect(page).toHaveURL(/\/workshops$/)
  await expect(overview.getByRole('link', { name: title })).toBeVisible()
  await expect(overview.getByRole('link', { name: /repair a puncture|adjust your brakes|service a gear system|true a wheel/i })).toHaveCount(0)

  await page.goto('/')
  const header = page.getByRole('banner')
  const mobileMenu = header.getByText('Browse Cookie Shop', { exact: true })
  if (await mobileMenu.isVisible()) await mobileMenu.press('Enter')
  await header.getByRole('link', { name: 'Workshops', exact: true }).press('Enter')
  await expect(page).toHaveURL(/\/workshops$/)
  await page.goto('/cookies')
  await page.getByRole('link', { name: 'Explore our workshops', exact: true }).press('Enter')
  await expect(page).toHaveURL(/\/workshops$/)
  await page.goto('/')
  await preview.getByRole('link', { name: 'Explore our workshops' }).press('Enter')
  await expect(page).toHaveURL(/\/workshops$/)
  await page.goto('/')
  await page.getByRole('contentinfo').getByRole('link', { name: 'Workshops', exact: true }).press('Enter')
  await expect(page).toHaveURL(/\/workshops$/)
})
